      onShare!();
    }
  }

  @override
  Widget build(BuildContext context) {
    return Row(
      mainAxisSize: MainAxisSize.min,
      children: [
        Container(
          decoration: BoxDecoration(
            gradient:
                AppStyles.gradientAccent, // Use gradient instead of solid color
